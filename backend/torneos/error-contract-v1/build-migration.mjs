// ERROR-CONTRACT-V1 — builds migration 00000000000006_domain_error_contract.sql and its rollback from the
// LOCAL lab catalog (integration/torneos-core-contracts, read-only) and contract.json.
//
// Every replaced body is derived byte for byte from the body in force (pg_get_functiondef + prosrc): inside each
// RAISE statement that carries a contract message, ONLY the errcode literal changes (legacy SQLSTATE → PTxyz, the
// PostgREST custom-status form). Nothing else in any body moves. The lab may be at POST_0005 (forward) or already
// at POST_0006 (the POST_0005 body is recovered by the exact reverse edit, and must hash to the pinned md5).
//
//   node backend/torneos/error-contract-v1/build-migration.mjs --write   # regenerate files + contract pins
//   node backend/torneos/error-contract-v1/build-migration.mjs --check   # regenerated bytes == committed files
//
// Local only: the catalog is read through `docker compose exec` of the lab's torneos-db. Nothing remote.
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { sql } from '../../../integration/torneos-core-contracts/lab.mjs';

const here = fileURLToPath(new URL('.', import.meta.url));
const repo = fileURLToPath(new URL('../../../', import.meta.url));
const CONTRACT = `${here}contract.json`;
const MIGRATION = 'backend/torneos/supabase/migrations/00000000000006_domain_error_contract.sql';
const ROLLBACK = 'backend/torneos/error-contract-v1/rollback/00000000000006_domain_error_contract.rollback.sql';
const RAISE = /raise\s+exception\b[^;]*;/gi;
const md5 = (s) => createHash('md5').update(s, 'utf8').digest('hex');
const sha256 = (s) => createHash('sha256').update(s, 'utf8').digest('hex');
const lit = (v) => `'${String(v).replace(/'/g, "''")}'`;

export const ptOf = (contract, message) => {
  const status = contract.http[message];
  if (!Number.isInteger(status)) throw new Error(`no HTTP status for ${message}`);
  return `PT${status}`;
};

/** The exact edit: errcode literal of every RAISE carrying one of `raises`' messages, `from` → `to`. */
export function edit(src, raises, contract, direction) {
  const seen = new Map();
  const out = src.replace(RAISE, (stmt) => {
    const hits = raises.filter((r) => stmt.includes(`'${r.message}'`));
    if (hits.length === 0) return stmt;
    if (hits.length > 1) throw new Error(`one RAISE carries several contract messages: ${stmt.slice(0, 120)}`);
    const [r] = hits;
    const [from, to] = direction === 'forward' ? [r.from, ptOf(contract, r.message)] : [ptOf(contract, r.message), r.from];
    const re = new RegExp(`(errcode\\s*=\\s*')${from}(')`, 'i');
    if (!re.test(stmt)) throw new Error(`${r.message}: expected errcode '${from}' (${direction}) in: ${stmt.replace(/\s+/g, ' ').slice(0, 160)}`);
    seen.set(r.message, (seen.get(r.message) ?? 0) + 1);
    return stmt.replace(re, `$1${to}$2`);
  });
  for (const r of raises) {
    if ((seen.get(r.message) ?? 0) !== r.count) throw new Error(`${r.message}: ${seen.get(r.message) ?? 0} RAISE(s) edited, contract says ${r.count}`);
  }
  return out;
}

function catalog(contract) {
  const sigs = contract.changes.map((c) => c.function);
  const rows = JSON.parse(sql('torneos-db', `select json_agg(json_build_object('f', f, 'def', pg_get_functiondef(to_regprocedure(f)), 'src', p.prosrc) order by ord)
    from unnest(array[${sigs.map(lit).join(',')}]) with ordinality u(f, ord) left join pg_proc p on p.oid = to_regprocedure(f)`));
  for (const row of rows) if (!row.src) throw new Error(`missing in the lab catalog: ${row.f}`);
  return rows;
}

/** POST_0005 and POST_0006 bodies + full definitions for every contract function. */
export function derive(contract, rows) {
  return contract.changes.map((change, i) => {
    const { f, def, src } = rows[i];
    if (f !== change.function) throw new Error(`catalog order ${f} ≠ ${change.function}`);
    if (src.includes('$function$')) throw new Error(`${f}: body contains the $function$ delimiter`);
    const wrapped = `AS $function$${src}$function$`;
    if (def.split(wrapped).length !== 2) throw new Error(`${f}: pg_get_functiondef does not wrap prosrc exactly once`);
    let before; let after;
    try { after = edit(src, change.raises, contract, 'forward'); before = src; } catch (forwardError) {
      try { before = edit(src, change.raises, contract, 'reverse'); after = src; } catch {
        throw new Error(`${f}: body is neither POST_0005 nor POST_0006 (${forwardError.message})`);
      }
    }
    if (edit(before, change.raises, contract, 'forward') !== after || edit(after, change.raises, contract, 'reverse') !== before) {
      throw new Error(`${f}: the edit is not an exact involution`);
    }
    const head = def.slice(0, def.indexOf(wrapped));
    const tail = def.slice(def.indexOf(wrapped) + wrapped.length);
    const definition = (body) => `${head}AS $function$${body}$function$${tail.replace(/\s*$/, '')};\n`;
    return { change, before, after, md5Before: md5(before), md5After: md5(after), defBefore: definition(before), defAfter: definition(after) };
  });
}

const pinArray = (items, key1, key2) => `array[\n${items.map((d) => `    array[${lit(d.change.function)}, ${lit(d[key1])}, ${lit(d[key2])}]`).join(',\n')}\n  ]`;

// Catalog-wide postcondition over v_codes (message, PTxyz, expected RAISE count).
function sweepBlock(tag) {
  return `  -- Catalog sweep (public + private): each contract message is raised exactly the expected number of times,
  -- always with its PTxyz code; no function raises SQLSTATE 40001 (reserved for the engine's own serialization failures).
  FOR i IN 1 .. array_length(v_codes, 1) LOOP
    SELECT count(*) FILTER (WHERE m[1] ~* ('errcode\\s*=\\s*''' || v_codes[i][2] || '''')),
           count(*) FILTER (WHERE m[1] !~* ('errcode\\s*=\\s*''' || v_codes[i][2] || ''''))
      INTO v_ok, v_bad
    FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace,
         regexp_matches(p.prosrc, '(raise\\s+exception[^;]*;)', 'gi') m
    WHERE n.nspname IN ('public', 'private') AND strpos(m[1], '''' || v_codes[i][1] || '''') > 0;
    IF v_bad <> 0 OR v_ok <> v_codes[i][3]::integer THEN
      v_problems := v_problems || format('%s raised %s time(s) with %s and %s time(s) otherwise (expected %s)', v_codes[i][1], v_ok, v_codes[i][2], v_bad, v_codes[i][3]);
    END IF;
  END LOOP;
  IF EXISTS (SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
             WHERE n.nspname IN ('public', 'private') AND p.prosrc ~* 'errcode\\s*=\\s*''40001''') THEN
    v_problems := v_problems || '${tag}: a function raises SQLSTATE 40001'::text;
  END IF;
`;
}

export function render(contract, derived) {
  const n = derived.length;
  const raises = derived.reduce((a, d) => a + d.change.raises.reduce((b, r) => b + r.count, 0), 0);
  const table = derived.flatMap((d) => d.change.raises.map((r) => `--   ${d.change.function.split('(')[0].padEnd(46)} ${r.message.padEnd(46)} ${r.from} → ${ptOf(contract, r.message)} (${contract.http[r.message]})${r.count > 1 ? ` ×${r.count}` : ''}`)).join('\n');
  const snapshot = `CREATE TEMPORARY TABLE torneos_error_contract_v1_state (
  fn text PRIMARY KEY,
  attrs text NOT NULL
) ON COMMIT DROP;
CREATE TEMPORARY TABLE torneos_error_contract_v1_acl (
  authenticated_public integer NOT NULL,
  anon_public integer NOT NULL
) ON COMMIT DROP;
`;
  // Everything about a function except its body: owner, ACL, SECURITY DEFINER, config, volatility, signature/return.
  const attrs = `concat_ws('|', pg_get_userbyid(p.proowner), coalesce(p.proacl::text, 'default'), p.prosecdef, coalesce(p.proconfig::text, ''),
                  p.provolatile, p.proparallel, p.proretset, p.prorettype::regtype, p.prokind, p.prolang)`;
  const counts = `SELECT count(*) FILTER (WHERE has_function_privilege('authenticated', p.oid, 'EXECUTE')),
         count(*) FILTER (WHERE has_function_privilege('anon', p.oid, 'EXECUTE'))`;
  const sweepCodes = (() => {
    const expected = new Map();
    for (const c of contract.changes) for (const r of c.raises) expected.set(r.message, (expected.get(r.message) ?? 0) + r.count);
    return [...expected].map(([m, k]) => `    array[${lit(m)}, ${lit(ptOf(contract, m))}, ${lit(String(k))}]`).join(',\n');
  })();
  const sweep = sweepBlock('POSTCONDITION');

  const migration = `-- Arma2 Torneos — ERROR-CONTRACT-V1: expected domain errors answer 4xx with their functional code.
-- Applies after 00000000000000 … 00000000000005 (all unchanged). Append-only. Remote order: POST_0004 → 0005 → 0006
-- (set_tournament_match_dual_control, introduced by 0005, is one of the replaced bodies).
--
-- GENERATED by backend/torneos/error-contract-v1/build-migration.mjs from contract.json and the POST_0005 catalog of
-- the local lab. Do not edit by hand: regenerate, and \`--check\` proves the bytes.
--
-- Root cause (measured in the local lab, PostgREST v14.15):
--   • SQLSTATE 55000 / 54000 (and 55P03 / P0002) → HTTP 500; the frontend transport treated every ≥500 as an outage:
--     it dropped the bridge bearer and showed "Torneos no disponible" for ordinary conflicts and limits;
--   • SQLSTATE 40001 is RETRIED by PostgREST inside the same request: a deterministic domain 40001 was re-raised
--     thousands of times until the gateway's 5 s timeout answered 503 (retry storm, O(n) rollbacks per click).
--
-- What this migration does (one transaction, fail-closed pre/postconditions): in ${n} functions, ${raises} RAISE
-- statements keep their message, detail and control flow and change ONLY their errcode literal to the PostgREST
-- custom-status form PTxyz (HTTP xyz, same { code, message, details, hint } body). One code, one status everywhere
-- it is raised. No grant, owner, SECURITY DEFINER, search_path, signature or other statement changes.
--
-- function                                       message                                        SQLSTATE (HTTP)
${table}
--
-- Unchanged on purpose (see contract.json "unchanged"): invariants (make_tournament_match_official REVIEW_OPEN /
-- CORRECTION_STALE, media storage path, INTO STRICT reads), media pipeline readiness, commerce (own route, OFF,
-- and 55000 is caught by unordered_tournament_payment_reversal), true engine 40001 / 40P01 / 55P03.
--
-- Fail-closed: every replaced body must be exactly the certified POST_0005 body or this migration's (re-apply is a
-- no-op); anything else aborts with TORNEOS_ERROR_CONTRACT_V1_PRECONDITION_FAILED before any change. Rollback
-- (documented, never applied automatically): ${ROLLBACK}.
BEGIN;

${snapshot}
DO $pre$
DECLARE
  -- function, POST_0005 md5(prosrc), ERROR-CONTRACT-V1 md5(prosrc)
  v_pins text[][] := ${pinArray(derived, 'md5Before', 'md5After')};
  v_problems text[] := array[]::text[];
  v_md5 text;
  i integer;
BEGIN
  -- OFFICIALIZATION-V1 (0005) must be in force.
  IF to_regclass('public.tournament_organization_invitations') IS NULL
    OR NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'tournaments'
                   AND column_name = 'match_result_dual_control_enabled') THEN
    v_problems := v_problems || '0005 (OFFICIALIZATION-V1) not in force'::text;
  END IF;
  FOR i IN 1 .. array_length(v_pins, 1) LOOP
    IF to_regprocedure(v_pins[i][1]) IS NULL THEN
      v_problems := v_problems || ('missing ' || v_pins[i][1]);
      CONTINUE;
    END IF;
    SELECT md5(p.prosrc) INTO v_md5 FROM pg_proc p WHERE p.oid = to_regprocedure(v_pins[i][1]);
    IF v_md5 IS DISTINCT FROM v_pins[i][2] AND v_md5 IS DISTINCT FROM v_pins[i][3] THEN
      v_problems := v_problems || format('%s body %s is neither the certified POST_0005 nor the ERROR-CONTRACT-V1 body', v_pins[i][1], v_md5);
    END IF;
  END LOOP;
  IF cardinality(v_problems) > 0 THEN
    RAISE EXCEPTION 'TORNEOS_ERROR_CONTRACT_V1_PRECONDITION_FAILED: %', array_to_string(v_problems, '; ');
  END IF;
  INSERT INTO torneos_error_contract_v1_state
  SELECT v_pins[k][1], ${attrs}
  FROM generate_subscripts(v_pins, 1) k JOIN pg_proc p ON p.oid = to_regprocedure(v_pins[k][1]);
  INSERT INTO torneos_error_contract_v1_acl
  ${counts}
  FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
  WHERE n.nspname = 'public' AND p.prokind = 'f';
END $pre$;

-- ============================================================================ replaced bodies (errcode literals only)
${derived.map((d) => `-- ${d.change.function}: ${d.change.raises.map((r) => `${r.message} ${r.from} → ${ptOf(contract, r.message)}`).join('; ')}\n${d.defAfter}`).join('\n')}
DO $post$
DECLARE
  v_pins text[][] := ${pinArray(derived, 'md5Before', 'md5After')};
  -- message, PTxyz, number of RAISE statements carrying it across the catalog
  v_codes text[][] := array[
${sweepCodes}
  ];
  v_problems text[] := array[]::text[];
  v_before torneos_error_contract_v1_acl%rowtype;
  v_auth integer;
  v_anon integer;
  v_ok integer;
  v_bad integer;
  i integer;
BEGIN
  FOR i IN 1 .. array_length(v_pins, 1) LOOP
    IF (SELECT md5(p.prosrc) FROM pg_proc p WHERE p.oid = to_regprocedure(v_pins[i][1])) IS DISTINCT FROM v_pins[i][3] THEN
      v_problems := v_problems || ('body not pinned: ' || v_pins[i][1]);
    END IF;
  END LOOP;
  IF EXISTS (SELECT 1 FROM torneos_error_contract_v1_state s JOIN pg_proc p ON p.oid = to_regprocedure(s.fn)
             WHERE s.attrs IS DISTINCT FROM ${attrs.replace(/\n\s*/g, ' ')}) THEN
    v_problems := v_problems || 'owner / ACL / definer / config / signature of a replaced function changed'::text;
  END IF;
  SELECT * INTO v_before FROM torneos_error_contract_v1_acl;
  ${counts}
    INTO v_auth, v_anon
  FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
  WHERE n.nspname = 'public' AND p.prokind = 'f';
  IF v_auth <> v_before.authenticated_public OR v_anon <> v_before.anon_public THEN
    v_problems := v_problems || format('client catalog changed: authenticated %s -> %s, anon %s -> %s',
      v_before.authenticated_public, v_auth, v_before.anon_public, v_anon);
  END IF;
${sweep}  IF cardinality(v_problems) > 0 THEN
    RAISE EXCEPTION 'TORNEOS_ERROR_CONTRACT_V1_POSTCONDITION_FAILED: %', array_to_string(v_problems, '; ');
  END IF;
END $post$;

COMMIT;
`;

  const rollback = `-- Arma2 Torneos — ERROR-CONTRACT-V1 ROLLBACK (not a migration; documented, never applied automatically).
-- GENERATED by backend/torneos/error-contract-v1/build-migration.mjs. Restores the ${n} certified POST_0005 bodies byte for
-- byte (md5 pinned): the ${raises} RAISE statements get their legacy SQLSTATE back. Nothing else changes (no grant, no table).
-- Effect: expected domain errors answer 500 again and the three former 40001 raises re-enter PostgREST's retry loop;
-- the gateway's legacy-SQLSTATE defense still maps the 55000 / 54000 ones (not 40001). Order: DB rollback only when
-- the frontend/gateway no longer depend on the 4xx contract; the gateway defense can stay.
BEGIN;

${snapshot}
DO $pre$
DECLARE
  v_pins text[][] := ${pinArray(derived, 'md5Before', 'md5After')};
  v_problems text[] := array[]::text[];
  v_md5 text;
  i integer;
BEGIN
  FOR i IN 1 .. array_length(v_pins, 1) LOOP
    SELECT md5(p.prosrc) INTO v_md5 FROM pg_proc p WHERE p.oid = to_regprocedure(v_pins[i][1]);
    IF v_md5 IS DISTINCT FROM v_pins[i][3] AND v_md5 IS DISTINCT FROM v_pins[i][2] THEN
      v_problems := v_problems || format('%s body %s is neither the ERROR-CONTRACT-V1 nor the POST_0005 body', v_pins[i][1], coalesce(v_md5, 'missing'));
    END IF;
  END LOOP;
  IF cardinality(v_problems) > 0 THEN
    RAISE EXCEPTION 'TORNEOS_ERROR_CONTRACT_V1_ROLLBACK_PRECONDITION_FAILED: %', array_to_string(v_problems, '; ');
  END IF;
  INSERT INTO torneos_error_contract_v1_state
  SELECT v_pins[k][1], ${attrs}
  FROM generate_subscripts(v_pins, 1) k JOIN pg_proc p ON p.oid = to_regprocedure(v_pins[k][1]);
  INSERT INTO torneos_error_contract_v1_acl
  ${counts}
  FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
  WHERE n.nspname = 'public' AND p.prokind = 'f';
END $pre$;

${derived.map((d) => `-- ${d.change.function}: POST_0005 body\n${d.defBefore}`).join('\n')}
DO $post$
DECLARE
  v_pins text[][] := ${pinArray(derived, 'md5Before', 'md5After')};
  v_problems text[] := array[]::text[];
  v_before torneos_error_contract_v1_acl%rowtype;
  v_auth integer;
  v_anon integer;
  i integer;
BEGIN
  FOR i IN 1 .. array_length(v_pins, 1) LOOP
    IF (SELECT md5(p.prosrc) FROM pg_proc p WHERE p.oid = to_regprocedure(v_pins[i][1])) IS DISTINCT FROM v_pins[i][2] THEN
      v_problems := v_problems || ('body not restored: ' || v_pins[i][1]);
    END IF;
  END LOOP;
  IF EXISTS (SELECT 1 FROM torneos_error_contract_v1_state s JOIN pg_proc p ON p.oid = to_regprocedure(s.fn)
             WHERE s.attrs IS DISTINCT FROM ${attrs.replace(/\n\s*/g, ' ')}) THEN
    v_problems := v_problems || 'owner / ACL / definer / config / signature of a restored function changed'::text;
  END IF;
  SELECT * INTO v_before FROM torneos_error_contract_v1_acl;
  ${counts}
    INTO v_auth, v_anon
  FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
  WHERE n.nspname = 'public' AND p.prokind = 'f';
  IF v_auth <> v_before.authenticated_public OR v_anon <> v_before.anon_public THEN
    v_problems := v_problems || 'client catalog changed'::text;
  END IF;
  IF cardinality(v_problems) > 0 THEN
    RAISE EXCEPTION 'TORNEOS_ERROR_CONTRACT_V1_ROLLBACK_POSTCONDITION_FAILED: %', array_to_string(v_problems, '; ');
  END IF;
END $post$;

COMMIT;
`;
  // Own temp-table names: the rollback can be proven in the same transaction right after the migration.
  return { migration, rollback: rollback.replace(/torneos_error_contract_v1_(state|acl)\b/g, 'torneos_error_contract_v1_rollback_$1') };
}

async function main() {
  const mode = process.argv[2];
  if (!['--write', '--check'].includes(mode)) throw new Error('usage: build-migration.mjs --write | --check');
  const contract = JSON.parse(await readFile(CONTRACT, 'utf8'));
  const derived = derive(contract, catalog(contract));
  const { migration, rollback } = render(contract, derived);
  const pins = derived.map((d) => ({ function: d.change.function, md5_before: d.md5Before, md5_after: d.md5After }));
  if (mode === '--check') {
    const problems = [];
    if (await readFile(`${repo}${MIGRATION}`, 'utf8') !== migration) problems.push(`${MIGRATION} differs from the regenerated bytes`);
    if (await readFile(`${repo}${ROLLBACK}`, 'utf8') !== rollback) problems.push(`${ROLLBACK} differs from the regenerated bytes`);
    if (JSON.stringify(contract.migration.pins) !== JSON.stringify(pins)) problems.push('contract.json pins differ');
    if (contract.migration.sha256 !== sha256(migration) || contract.migration.rollback_sha256 !== sha256(rollback)) problems.push('contract.json sha256 differ');
    if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
    console.log(JSON.stringify({ check: 'PASS', functions: pins.length, sha256: sha256(migration), rollback_sha256: sha256(rollback) }));
    return;
  }
  await writeFile(`${repo}${MIGRATION}`, migration);
  await writeFile(`${repo}${ROLLBACK}`, rollback);
  contract.migration.sha256 = sha256(migration);
  contract.migration.rollback = ROLLBACK;
  contract.migration.rollback_sha256 = sha256(rollback);
  contract.migration.pins = pins;
  await writeFile(CONTRACT, JSON.stringify(contract, null, 2) + '\n');
  console.log(JSON.stringify({ written: [MIGRATION, ROLLBACK], sha256: contract.migration.sha256, functions: pins.length }));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
