#!/usr/bin/env node

import process from 'node:process';
import { spawnSync } from 'node:child_process';
import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { createClient } from '@supabase/supabase-js';

import productionGuard from './production-guard.js';
import {
  QA_USER_ROLES,
  SEED_KEY,
} from './torneos-demo-manifest.mjs';
import {
  QAIdentityMap,
  QA_IDENTITY_RELATIONS,
} from './torneos-qa-identity-map.mjs';
import { withDatabase } from './torneos-seed-db.mjs';

const {
  assertLocalDatabaseTarget,
  assertRemoteApplyDisabled,
  assertRemotePlanTarget,
  assertSafeQaEnvironment,
} = productionGuard;

const DISPLAY_NAMES = Object.freeze({
  owner: 'QA Owner Torneos',
  admin: 'QA Admin Torneos',
  collaborator: 'QA Collaborator Torneos',
  delegate: 'QA Delegate Torneos',
  player: 'QA Player Torneos',
  outsider: 'QA Outsider Torneos',
});

export function localExpectedEmails(env = process.env) {
  return Object.fromEntries(QA_USER_ROLES.map((role) => [
    role,
    String(
      env[`QA_IDENTITY_${role.toUpperCase()}_EMAIL`]
      || `qa-${role}@localhost.invalid`,
    ).trim().toLowerCase(),
  ]));
}

function userPlan() {
  return {
    roles: QA_USER_ROLES.map((role) => ({
      role,
      authUserId: '[generated by Supabase Auth; never supplied by the seed]',
      expectedEmail: '[secure input; never printed]',
      projectedRelations: QA_IDENTITY_RELATIONS[role],
      profile: 'public.usuarios (must be created by the canonical Auth sync trigger)',
    })),
    forbiddenIdentityMapFields: [
      'password',
      'refresh_token',
      'access_token',
      'service_role',
      'secret_key',
    ],
    remoteAdministrativeOperation: {
      status: 'blocked-pending-authorization-A',
      mechanism: 'server-side supabase.auth.admin.createUser without an id parameter',
      credentialInput: 'masked interactive input or secret environment outside Git',
      next: 'capture returned user.id values into a Git-ignored QAIdentityMap',
    },
  };
}

function createAuthAdmin(url, serviceRoleKey) {
  const parsed = new URL(url);
  if (!['127.0.0.1', 'localhost', '::1'].includes(parsed.hostname)) {
    throw new Error('Local Auth Admin URL must use a loopback hostname.');
  }
  if (!serviceRoleKey) throw new Error('QA_LOCAL_SERVICE_ROLE_KEY is required in memory.');
  return createClient(url, serviceRoleKey, {
    auth: {
      autoRefreshToken: false,
      persistSession: false,
      detectSessionInUrl: false,
    },
  }).auth.admin;
}

async function inspectByEmail(client, role, expectedEmail) {
  const result = await client.query(
    `select id, email, raw_app_meta_data
     from auth.users
     where lower(email) = $1`,
    [expectedEmail],
  );
  if (result.rowCount > 1) {
    throw new Error(`QA Auth preflight rejected duplicate email for role ${role}.`);
  }
  if (result.rowCount === 0) return null;
  const row = result.rows[0];
  if (
    row.raw_app_meta_data?.qa_seed_key !== SEED_KEY
    || row.raw_app_meta_data?.qa_role !== role
  ) {
    throw new Error(`QA Auth preflight rejected personal or foreign user for role ${role}.`);
  }
  return row;
}

async function waitForSyncedProfile(client, userId, expectedEmail) {
  for (let attempt = 0; attempt < 20; attempt += 1) {
    const profile = await client.query(
      'select email from public.usuarios where id = $1',
      [userId],
    );
    if (
      profile.rowCount === 1
      && String(profile.rows[0].email || '').toLowerCase() === expectedEmail
    ) {
      return;
    }
    await new Promise((resolve) => setTimeout(resolve, 25));
  }
  throw new Error('Canonical public.usuarios Auth sync did not complete.');
}

export async function createLocalUsers({
  client,
  authAdmin,
  expectedEmails = localExpectedEmails(),
}) {
  const resolved = {};
  const createdRoles = [];
  for (const role of QA_USER_ROLES) {
    const expectedEmail = expectedEmails[role];
    let authUser = await inspectByEmail(client, role, expectedEmail);
    if (!authUser) {
      const { data, error } = await authAdmin.createUser({
        email: expectedEmail,
        email_confirm: true,
        app_metadata: {
          qa_seed_key: SEED_KEY,
          qa_role: role,
        },
        user_metadata: {
          full_name: DISPLAY_NAMES[role],
        },
      });
      if (error || !data?.user?.id) {
        throw new Error(`Supabase Auth failed to create QA role ${role}: ${error?.code || 'unknown'}`);
      }
      authUser = {
        id: data.user.id,
        email: data.user.email,
        raw_app_meta_data: data.user.app_metadata,
      };
      createdRoles.push(role);
    }
    await waitForSyncedProfile(client, authUser.id, expectedEmail);
    resolved[role] = {
      auth_user_id: authUser.id,
      expected_email: expectedEmail,
      logical_role: role,
      projected_relations: QA_IDENTITY_RELATIONS[role],
    };
  }
  const identityMap = new QAIdentityMap(resolved);
  return {
    status: 'ready',
    createdCount: createdRoles.length,
    reusedSeedOwnedCount: QA_USER_ROLES.length - createdRoles.length,
    identityMap,
    identityMapFingerprint: identityMap.fingerprint(),
    report: identityMap.report(),
  };
}

export async function persistIdentityMapToIgnoredFile(identityMap, outputPath) {
  if (!outputPath) throw new Error('QA_IDENTITY_MAP_OUTPUT is required.');
  const absolutePath = resolve(outputPath);
  const ignored = spawnSync('git', ['check-ignore', '--quiet', '--', absolutePath], {
    cwd: process.cwd(),
    stdio: 'ignore',
  });
  if (ignored.status !== 0) {
    throw new Error('Identity map output must already be covered by .gitignore.');
  }
  await writeFile(
    absolutePath,
    `${JSON.stringify(identityMap.toJSON(), null, 2)}\n`,
    { encoding: 'utf8', mode: 0o600, flag: 'wx' },
  );
  return absolutePath;
}

export async function cleanupLocalUsers({
  client,
  authAdmin,
  identityMap,
}) {
  const present = [];
  for (const role of QA_USER_ROLES) {
    const identity = identityMap.get(role);
    const auth = await client.query(
      `select id, email, raw_app_meta_data
       from auth.users where id = $1`,
      [identity.auth_user_id],
    );
    if (!auth.rowCount) continue;
    if (
      String(auth.rows[0].email).toLowerCase() !== identity.expected_email
      || auth.rows[0].raw_app_meta_data?.qa_seed_key !== SEED_KEY
      || auth.rows[0].raw_app_meta_data?.qa_role !== role
    ) {
      throw new Error(`Ownership proof failed for QA user role ${role}.`);
    }
    const references = await client.query(
      `select (
        (select count(*) from public.tournament_organization_members where user_id = $1)
        + (select count(*) from public.tournament_team_managers where user_id = $1)
        + (select count(*) from public.tournament_roster_players where arma2_user_id = $1)
      )::integer as count`,
      [identity.auth_user_id],
    );
    if (references.rows[0].count !== 0) {
      throw new Error(`QA user role ${role} is still referenced by tournament data.`);
    }
    present.push({ role, id: identity.auth_user_id });
  }
  for (const user of present) {
    const { error } = await authAdmin.deleteUser(user.id);
    if (error) throw new Error(`Auth deletion failed for QA role ${user.role}: ${error.code}`);
    const profile = await client.query(
      'select 1 from public.usuarios where id = $1',
      [user.id],
    );
    if (profile.rowCount !== 0) {
      throw new Error(`Synced profile remained after Auth deletion for role ${user.role}.`);
    }
  }
  return { status: present.length ? 'cleaned' : 'already_clean', deleted: present.length };
}

async function main() {
  const args = new Set(process.argv.slice(2));
  if (args.has('--apply') || args.has('--apply-remote')) assertRemoteApplyDisabled();
  if (args.has('--remote-plan')) {
    const target = assertRemotePlanTarget(process.env);
    console.log(JSON.stringify({
      mode: 'remote-user-plan-only',
      connects: false,
      target,
      ...userPlan(),
    }, null, 2));
    return;
  }
  if (args.has('--apply-local')) {
    const target = assertLocalDatabaseTarget(process.env);
    if (process.env.QA_ALLOW_LOCAL_USER_PREP !== 'true') {
      throw new Error('QA_ALLOW_LOCAL_USER_PREP=true is required.');
    }
    const authAdmin = createAuthAdmin(
      process.env.QA_SUPABASE_URL,
      process.env.QA_LOCAL_SERVICE_ROLE_KEY,
    );
    const result = await withDatabase(target.databaseUrl, (client) => createLocalUsers({
      client,
      authAdmin,
      expectedEmails: localExpectedEmails(process.env),
    }));
    const identityMapWritten = process.env.QA_IDENTITY_MAP_OUTPUT
      ? Boolean(await persistIdentityMapToIgnoredFile(
        result.identityMap,
        process.env.QA_IDENTITY_MAP_OUTPUT,
      ))
      : false;
    console.log(JSON.stringify({
      mode: 'local-user-apply',
      createdCount: result.createdCount,
      reusedSeedOwnedCount: result.reusedSeedOwnedCount,
      identityMapFingerprint: result.identityMapFingerprint,
      identities: result.report,
      identityMapWritten,
      note: identityMapWritten
        ? 'Full map written mode 0600 to the requested Git-ignored path; path and emails omitted.'
        : 'Set QA_IDENTITY_MAP_OUTPUT to a new Git-ignored path to persist the full map mode 0600.',
    }, null, 2));
    return;
  }
  if (args.size > 0 && !args.has('--dry-run')) {
    throw new Error('Use --dry-run, --remote-plan, or --apply-local.');
  }
  assertSafeQaEnvironment(process.env);
  console.log(JSON.stringify({
    mode: 'offline-user-plan',
    connects: false,
    writes: false,
    ...userPlan(),
  }, null, 2));
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  main().catch((error) => {
    console.error(JSON.stringify({ error: error.message }, null, 2));
    process.exitCode = 1;
  });
}
