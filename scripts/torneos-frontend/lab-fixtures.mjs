#!/usr/bin/env node
// B04 hybrid lab fixtures — lab-only (loopback Core of integration/torneos-core-contracts).
//
//   users     create the QA users in the lab GoTrue (signup, autoconfirmed)
//   core-team create a Core team owned by the owner (Core `teams`/`team_members`, like the
//             Phase 3A suite does) so the UI can import it through directory_teams/team_snapshot
//   connected-call  (lab gateway with TORNEOS_CONNECTED_MODE=on) the owner publishes a call in Explorar torneos
//             through the gateway, as the organizer UI does: organization, season, tournament, category, public page,
//             listing and open applications — three explicit steps. The captain gets a Core team to apply with.
//   login     print the app callback URL that establishes a Core session for <email>: the
//             magic-link token is generated by the lab admin API and verified server-side;
//             the app's own /auth/callback (setSession from the hash) completes the login.
//             The lab has no mailer, so this replaces "open the email".
//
// Never touches a remote host; the lab keys come from the lab .runtime and are never printed.
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const lab = path.join(root, 'integration/torneos-core-contracts');
const cfg = JSON.parse(fs.readFileSync(path.join(lab, '.runtime/config.json'), 'utf8'));
const CORE = 'http://127.0.0.1:58424';
const GATEWAY = 'http://127.0.0.1:58420';
const PROJECT = process.env.PHASE3A_LAB_PROJECT || 'arma2-b04-hybrid-lab';
const docker = '/Applications/Docker.app/Contents/Resources/bin/docker';
const USERS = {
  owner: { email: 'b04-owner@lab.test', name: 'B04 Owner' },
  captain: { email: 'b04-captain@lab.test', name: 'B04 Captain' },
  ana: { email: 'b04-ana@lab.test', name: 'Ana Lab Jugadora' },
  beto: { email: 'b04-beto@lab.test', name: 'Beto Lab Jugador' },
};
const PASSWORD = 'b04-lab-password-placeholder';

async function core(pathname, { method = 'POST', body, bearer = cfg.anonKey } = {}) {
  const r = await fetch(`${CORE}${pathname}`, {
    method, headers: { apikey: cfg.anonKey, authorization: `Bearer ${bearer}`, 'content-type': 'application/json' },
    body: body === undefined ? undefined : JSON.stringify(body), signal: AbortSignal.timeout(15000),
  });
  let json = null; try { json = await r.json(); } catch { /* empty */ }
  return { status: r.status, json };
}
function coreSql(query) {
  const r = spawnSync(docker, ['--host', 'unix:///var/run/docker.sock', 'compose', '--project-name', PROJECT, '--env-file', '.runtime/compose.env', '-f', 'compose.yaml', 'exec', '-T', 'core-db', 'psql', '-U', 'postgres', '-d', 'postgres', '-X', '-A', '-t', '-q', '-v', 'ON_ERROR_STOP=1'], { cwd: lab, input: query, encoding: 'utf8' });
  if (r.status !== 0) throw new Error(`core-db sql failed: ${(r.stderr || '').split('\n').filter((l) => l.startsWith('ERROR')).join(' ')}`);
  return r.stdout.trim();
}
const lit = (v) => `'${String(v).replace(/'/g, "''")}'`;

async function ensureUser({ email, name }) {
  const existing = coreSql(`select id from auth.users where email=${lit(email)}`);
  if (existing) return existing;
  const r = await core('/auth/v1/signup', { body: { email, password: PASSWORD, data: { full_name: name, nombre: name } } });
  if (r.status !== 200 || !r.json?.user?.id) throw new Error(`signup ${email} → ${r.status}`);
  return r.json.user.id;
}

async function torneosToken(user) {
  const session = await core('/auth/v1/token?grant_type=password', { body: { email: user.email, password: PASSWORD } });
  if (session.status !== 200 || !session.json?.access_token) throw new Error(`login ${user.email} → ${session.status}`);
  const exchanged = await fetch(`${GATEWAY}/exchange`, {
    method: 'POST', headers: { authorization: `Bearer ${session.json.access_token}` }, signal: AbortSignal.timeout(15000),
  });
  const body = await exchanged.json().catch(() => null);
  if (exchanged.status !== 200 || !body?.access_token) throw new Error(`exchange ${user.email} → ${exchanged.status}`);
  return body.access_token;
}

async function gatewayRpc(token, name, params) {
  const response = await fetch(`${GATEWAY}/torneos/rest/v1/rpc/${name}`, {
    method: 'POST',
    headers: { authorization: `Bearer ${token}`, 'content-type': 'application/json' },
    body: JSON.stringify(params), signal: AbortSignal.timeout(15000),
  });
  const json = await response.json().catch(() => null);
  if (response.status !== 200) throw new Error(`${name} → ${response.status} ${JSON.stringify(json).slice(0, 200)}`);
  return json;
}

const command = process.argv[2];
if (command === 'users') {
  for (const [key, user] of Object.entries(USERS)) console.log(`${key}\t${user.email}\t${await ensureUser(user)}`);
} else if (command === 'core-team') {
  const ownerId = coreSql(`select id from auth.users where email=${lit(USERS.owner.email)}`);
  if (!ownerId) throw new Error('run users first');
  const teamName = process.argv[3] || 'Lab Import FC';
  const existing = coreSql(`select id from public.teams where name=${lit(teamName)} and owner_user_id=${lit(ownerId)}`);
  if (existing) { console.log(`team\t${teamName}\t${existing}\t(existing)`); process.exit(0); }
  const id = coreSql(`insert into public.teams(owner_user_id, name, format) values (${lit(ownerId)}, ${lit(teamName)}, 5) returning id`);
  // Members the way the Phase 3A suite seeds them: a jugadores row per member (account
  // or not), inserted as the owner because Core's trigger only lets owner/admin write.
  for (const [key, member] of [['ana', 'member'], ['beto', 'member']]) {
    const user = USERS[key];
    const coreUserId = coreSql(`select id from auth.users where email=${lit(user.email)}`);
    const partido = coreSql('insert into public.partidos default values returning id');
    const jugador = coreSql(`insert into public.jugadores(partido_id, nombre, usuario_id) values (${partido}, ${lit(user.name)}, ${coreUserId ? lit(coreUserId) : 'null'}) returning id`);
    coreSql(`BEGIN; SELECT set_config('request.jwt.claims', ${lit(JSON.stringify({ sub: ownerId, role: 'authenticated' }))}, true);
      insert into public.team_members(team_id, jugador_id, user_id, permissions_role) values (${lit(id)}, ${jugador}, ${coreUserId ? lit(coreUserId) : 'null'}, ${lit(member)}); COMMIT;`);
  }
  console.log(`team\t${teamName}\t${id}\tmembers=2`);
} else if (command === 'connected-call') {
  for (const user of Object.values(USERS)) await ensureUser(user);
  const captainId = coreSql(`select id from auth.users where email=${lit(USERS.captain.email)}`);
  if (!coreSql(`select id from public.teams where name='Lab Halcones' and owner_user_id=${lit(captainId)}`)) {
    coreSql(`insert into public.teams(owner_user_id, name, format) values (${lit(captainId)}, 'Lab Halcones', 5)`);
  }
  const listed = await fetch(`${GATEWAY}/torneos/public/v1/rpc/search_tournament_catalog`, {
    method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ p_query: 'Lab Copa Conectada', p_scope: 'all' }),
  }).then((r) => r.json());
  if (listed?.total) { console.log(`call\talready listed (${listed.items[0].publicSlug})`); process.exit(0); }
  const token = await torneosToken(USERS.owner);
  await gatewayRpc(token, 'update_my_torneos_profile', { p_display_name: 'Lab Organización', p_notify_registration_requests: true });
  const key = () => crypto.randomUUID();
  const org = (await gatewayRpc(token, 'create_tournament_organization', { p_name: 'Lab Liga Conectada', p_slug: 'lab-liga-conectada', p_idempotency_key: key() })).organization.id;
  const season = (await gatewayRpc(token, 'create_tournament_season', { p_organization_id: org, p_name: 'Lab Temporada', p_slug: 'lab-temporada', p_start_date: null, p_end_date: null, p_idempotency_key: key() })).id;
  const tournament = (await gatewayRpc(token, 'create_tournament_with_defaults', { p_organization_id: org, p_season_id: season, p_name: 'Lab Copa Conectada', p_slug: 'lab-copa-conectada', p_description: null, p_sport_modality: 'football_5', p_competition_format: 'league', p_gender_category: 'open', p_start_date: null, p_end_date: null, p_idempotency_key: key() })).id;
  await gatewayRpc(token, 'save_tournament_category', { p_organization_id: org, p_tournament_id: tournament, p_category_id: null, p_name: 'Libre', p_slug: 'libre', p_description: null, p_sort_order: null, p_min_age: null, p_max_age: null, p_gender_category: null, p_sport_modality: null, p_team_size: null, p_status: 'active' });
  await gatewayRpc(token, 'change_tournament_status', { p_organization_id: org, p_tournament_id: tournament, p_status: 'registration' });
  const slug = (await gatewayRpc(token, 'set_tournament_public_page_published', { p_organization_id: org, p_tournament_id: tournament, p_published: true })).publicSlug;
  await gatewayRpc(token, 'save_tournament_catalog_listing', { p_organization_id: org, p_tournament_id: tournament, p_summary: 'Lab · Fútbol 5 los sábados en el laboratorio híbrido.', p_locality: 'Rosario', p_venue_id: null, p_entry_fee_cents: 0, p_entry_fee_includes: null, p_payment_note: null, p_requirements: null, p_rules_summary: null });
  await gatewayRpc(token, 'set_tournament_catalog_listing_status', { p_organization_id: org, p_tournament_id: tournament, p_listed: true });
  await gatewayRpc(token, 'set_tournament_applications_state', { p_organization_id: org, p_tournament_id: tournament, p_state: 'open' });
  console.log(`call\t${slug}\torganization=${org}\ttournament=${tournament}`);
} else if (command === 'login') {
  const email = process.argv[3];
  if (!email) throw new Error('login <email>');
  const link = await core('/auth/v1/admin/generate_link', { bearer: cfg.serviceRoleKey, body: { type: 'magiclink', email } });
  if (link.status !== 200 || !link.json?.hashed_token) throw new Error(`generate_link → ${link.status}`);
  const verified = await core('/auth/v1/verify', { body: { type: 'magiclink', token_hash: link.json.hashed_token } });
  if (verified.status !== 200 || !verified.json?.access_token) throw new Error(`verify → ${verified.status}`);
  const { access_token, refresh_token, expires_in } = verified.json;
  const fragment = new URLSearchParams({ access_token, refresh_token, token_type: 'bearer', type: 'magiclink', expires_in: String(expires_in) });
  console.log(`${process.env.B04_LAB_APP_ORIGIN || 'http://localhost:3000'}/auth/callback#${fragment.toString()}`);
} else {
  console.error('usage: lab-fixtures.mjs users | core-team [name] | connected-call | login <email>');
  process.exit(64);
}
