async function core(pathname, { method = 'POST', body, bearer = cfg.anonKey } = {}) {
  const r = await fetch(`${CORE}${pathname}`, {
    method, headers: { apikey: cfg.anonKey, authorization: `Bearer ${bearer}`, 'content-type': 'application/json' },
    body: body === undefined ? undefined : JSON.stringify(body), signal: AbortSignal.timeout(15000),
  });
  let json = null; try { json = await r.json(); } catch { /* empty */ }
  return { status: r.status, json };
}
function coreSql(query) {
  const r = spawnSync(docker, ['--host', 'unix:///var/run/docker.sock', 'compose', '--project-name', PROJECT, '--env-file', '.runtime/compose.env', '-f', 'compose.yaml', 'exec', '-T', 'core-db', 'psql', '-U', 'postgres', '-d', 'postgres', '-X', '-A', '-t', '-q', '-v', 'ON_ERROR_STOP=1'], { cwd: lab, input: query, encoding: 'utf8' });
  if (r.status !== 0) throw new Error(`core-db sql failed: ${(r.stderr || '').split('\n').filter((l) => l.startsWith('ERROR')).join(' ')}`);
  return r.stdout.trim();
}
const lit = (v) => `'${String(v).replace(/'/g, "''")}'`;

async function ensureUser({ email, name }) {
  const existing = coreSql(`select id from auth.users where email=${lit(email)}`);
  if (existing) return existing;
  const r = await core('/auth/v1/signup', { body: { email, password: PASSWORD, data: { full_name: name, nombre: name } } });
  if (r.status !== 200 || !r.json?.user?.id) throw new Error(`signup ${email} → ${r.status}`);
  return r.json.user.id;
}

async function torneosToken(user) {
  const session = await core('/auth/v1/token?grant_type=password', { body: { email: user.email, password: PASSWORD } });
  if (session.status !== 200 || !session.json?.access_token) throw new Error(`login ${user.email} → ${session.status}`);
  const exchanged = await fetch(`${GATEWAY}/exchange`, {
    method: 'POST', headers: { authorization: `Bearer ${session.json.access_token}` }, signal: AbortSignal.timeout(15000),
  });
  const body = await exchanged.json().catch(() => null);
  if (exchanged.status !== 200 || !body?.access_token) throw new Error(`exchange ${user.email} → ${exchanged.status}`);
  return body.access_token;
}

async function gatewayRpc(token, name, params) {
  const response = await fetch(`${GATEWAY}/torneos/rest/v1/rpc/${name}`, {
    method: 'POST',
    headers: { authorization: `Bearer ${token}`, 'content-type': 'application/json' },
    body: JSON.stringify(params), signal: AbortSignal.timeout(15000),
  });
  const json = await response.json().catch(() => null);
  if (response.status !== 200) throw new Error(`${name} → ${response.status} ${JSON.stringify(json).slice(0, 200)}`);
  return json;
}

// A lab crest: a round badge with a band and a stripe, RGBA PNG (no dependency).
function crc32(buffer) {
  let crc = ~0;
  for (const byte of buffer) { crc ^= byte; for (let bit = 0; bit < 8; bit += 1) crc = (crc >>> 1) ^ (0xedb88320 & -(crc & 1)); }
  return (~crc) >>> 0;
}
function crestPng([r, g, b], [r2, g2, b2], size = 192) {
  const raw = Buffer.alloc((size * 4 + 1) * size);
  for (let y = 0; y < size; y += 1) {
    raw[y * (size * 4 + 1)] = 0;
    for (let x = 0; x < size; x += 1) {
      const dx = x - size / 2 + 0.5; const dy = y - size / 2 + 0.5;
      const radius = Math.sqrt(dx * dx + dy * dy);
      const inside = radius <= size / 2 - 6;
      const rim = inside && radius > size / 2 - 18;
      const band = Math.abs(dy) < size / 9 || Math.abs(dx + dy * 0.4) < size / 22;
      const o = y * (size * 4 + 1) + 1 + x * 4;
      const [cr, cg, cb] = rim ? [255, 255, 255] : band ? [r2, g2, b2] : [r, g, b];
      raw[o] = cr; raw[o + 1] = cg; raw[o + 2] = cb; raw[o + 3] = inside ? 255 : 0;
    }
  }
  const chunk = (type, data) => {
    const len = Buffer.alloc(4); len.writeUInt32BE(data.length);
    const body = Buffer.concat([Buffer.from(type), data]);
    const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(body));
    return Buffer.concat([len, body, crc]);
  };
  const header = Buffer.alloc(13);
  header.writeUInt32BE(size, 0); header.writeUInt32BE(size, 4); header[8] = 8; header[9] = 6;
  return Buffer.concat([Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', header), chunk('IDAT', zlib.deflateSync(raw)), chunk('IEND', Buffer.alloc(0))]);
}
async function storeBranding(token, organizationId, kind, entityId, bytes) {
  const folder = { organization: 'organizations', tournament: 'tournaments', team: 'teams' }[kind];
  const objectPath = `${organizationId}/${folder}/${entityId}/${crypto.randomUUID()}.png`;
  const stored = await fetch(`${GATEWAY}/torneos/branding/v1/object/${objectPath}`, {
    method: 'POST', headers: { authorization: `Bearer ${token}`, 'content-type': 'image/png' }, body: bytes, signal: AbortSignal.timeout(15000),
  });
  if (stored.status !== 200) throw new Error(`branding object ${kind} → ${stored.status} ${(await stored.text()).slice(0, 120)}`);
  const reference = await gatewayRpc(token, 'set_tournament_branding_reference', {
    p_organization_id: organizationId, p_entity_kind: kind, p_entity_id: entityId, p_path: objectPath });
  if (reference?.previousPath) {
    await fetch(`${GATEWAY}/torneos/branding/v1/object/${reference.previousPath}`, { method: 'DELETE', headers: { authorization: `Bearer ${token}` } });
  }
  return objectPath;
}

