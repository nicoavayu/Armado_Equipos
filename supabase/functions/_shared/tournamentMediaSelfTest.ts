//
// The processor attests its capabilities to the database, and `uploadReady`
// is derived from that attestation. An attestation that is merely a hardcoded
// object would be exactly the kind of optimistic constant this pipeline exists
// to remove — so the processor proves the claim first, against real image
// bytes compiled into the bundle, and only then attests.
//
// The fixtures below are byte-for-byte copies of files in
// `scripts/edge-functions/fixtures/tournament-media/`, which the Node suite
// exercises far more thoroughly. Keeping a small subset inline is what lets a
// cold Edge Function certify itself with no network and no filesystem.

