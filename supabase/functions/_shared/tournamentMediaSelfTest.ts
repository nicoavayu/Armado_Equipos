export type ProcessorSelfTest = {
  passed: boolean
  checks: Record<string, boolean>
}

function expectRejection(
  bytes: Uint8Array, mime: string, code: string,
): boolean {
  try {
    verifyNormalizedImage(bytes, mime)
    return false
  } catch (error) {
    return error instanceof MediaImageError && error.code === code
  }
}

function withTrailingBytes(bytes: Uint8Array): Uint8Array {
  const out = new Uint8Array(bytes.length + 4)
  out.set(bytes)
  out.set([0x50, 0x4b, 0x03, 0x04], bytes.length) // a ZIP local header
  return out
}

/**
 * Runs every capability the processor is about to claim. A single false here
 * means the release does not attest, and uploads stay closed.
 */
export async function runProcessorSelfTest(): Promise<ProcessorSelfTest> {
  const checks: Record<string, boolean> = {}

  checks.sniffJpeg = sniffImageMime(PROBE_JPEG_8X8) === "image/jpeg"
  checks.sniffPng = sniffImageMime(PROBE_PNG_1X1) === "image/png"
  checks.sniffWebp = sniffImageMime(PROBE_WEBP_8X8) === "image/webp"
  checks.rejectsGif = sniffImageMime(GIF_8X8) === null

  try {
    const png = verifyNormalizedImage(PROBE_PNG_1X1, "image/png")
    checks.decodesPng = png.width === 1 && png.height === 1 && png.alreadyClean
  } catch {
    checks.decodesPng = false
  }
  try {
    const jpeg = verifyNormalizedImage(PROBE_JPEG_8X8, "image/jpeg")
    checks.decodesJpeg = jpeg.width === 8 && jpeg.height === 8 && jpeg.alreadyClean
  } catch {
    checks.decodesJpeg = false
  }
  try {
    const webp = verifyNormalizedImage(PROBE_WEBP_8X8, "image/webp")
    checks.decodesWebp = webp.width === 8 && webp.height === 8 && webp.alreadyClean
  } catch {
    checks.decodesWebp = false
  }

  checks.rejectsMimeLie = expectRejection(
    PROBE_PNG_1X1, "image/jpeg", "MEDIA_MIME_MISMATCH",
  )
  checks.rejectsSvg = expectRejection(
    new TextEncoder().encode('<?xml version="1.0"?><svg xmlns="http://www.w3.org/2000/svg"/>'),
    "image/png",
    "MEDIA_MIME_MISMATCH",
  )
  checks.rejectsExifOrientation = expectRejection(
    DIRTY_JPEG_EXIF, "image/jpeg", "MEDIA_ORIENTATION_NOT_NORMALIZED",
  )
  checks.rejectsPngMetadata = expectRejection(
    DIRTY_PNG_TEXT, "image/png", "MEDIA_METADATA_PRESENT",
  )
  checks.rejectsAnimation = expectRejection(
    ANIMATED_PNG, "image/png", "MEDIA_ANIMATION_UNSUPPORTED",
  )
  checks.rejectsTruncated = expectRejection(
    PROBE_PNG_1X1.subarray(0, PROBE_PNG_1X1.length - 6),
    "image/png",
    "MEDIA_CONTENT_CORRUPT",
  )
  checks.rejectsTrailingBytes = expectRejection(
    withTrailingBytes(PROBE_PNG_1X1), "image/png", "MEDIA_TRAILING_BYTES",
  )

  // Metadata stripping is enforced, not applied — but the stripper still has to
  // find the carriers, otherwise "already clean" would be vacuously true.
  try {
    verifyNormalizedImage(DIRTY_PNG_TEXT, "image/png")
    checks.findsMetadataCarriers = false
  } catch (error) {
    checks.findsMetadataCarriers = error instanceof MediaImageError
      && error.message.includes("PNG:tEXt")
  }

  const digest = await sha256Hex(new TextEncoder().encode("arma2"))
  checks.checksumVerification = /^[0-9a-f]{64}$/.test(digest)

  const geometry = variantGeometry("thumbnail", 4000, 3000)
  checks.variantGeometry = geometry.width === 320 && geometry.height === 240
  const noUpscale = variantGeometry("detail", 100, 50)
  checks.variantNeverUpscales = noUpscale.width === 100 && noUpscale.height === 50

  return {
    passed: Object.values(checks).every(Boolean),
    checks,
  }
}
