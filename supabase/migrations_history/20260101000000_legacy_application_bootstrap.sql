create extension if not exists pgcrypto;

-- Supabase installs pgcrypto in the non-exposed `extensions` schema. The
-- tournament RPCs qualify this compatibility helper as `public.digest`.
create function public.digest(data text, type text)
returns bytea
language sql
immutable
strict
set search_path = ''
as $$
  select extensions.digest(data, type)
$$;

