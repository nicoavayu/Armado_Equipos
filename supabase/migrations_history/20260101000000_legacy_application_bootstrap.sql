create view public.notifications_ext
with (security_invoker = true)
as
select
  n.*,
  p.nombre as partido_nombre,
  p.fecha as partido_fecha,
  p.hora as partido_hora,
  p.sede as partido_sede
from public.notifications n
left join public.partidos p on p.id = n.partido_id;

create view public.partidos_view
with (security_invoker = true)
as
select p.*
from public.partidos p
where p.deleted_at is null;

create view public.partidos_jugadores
with (security_invoker = true)
as
select
  p.id as partido_id,
  j.id as jugador_id,
  j.usuario_id,
  j.nombre,
  j.avatar_url,
  j.score,
  j.is_goalkeeper
from public.partidos p
join public.jugadores j on j.partido_id = p.id;

